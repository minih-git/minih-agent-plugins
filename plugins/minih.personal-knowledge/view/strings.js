/** The severity classes health mode colors by (design doc §8). */
export function classifyIssueCode(code) {
  if (String(code).startsWith("UNKNOWN_")) return "red";
  if (
    code === "DOMAIN_VIOLATION" ||
    code === "RANGE_VIOLATION" ||
    code === "CARDINALITY_VIOLATION" ||
    code === "LEGACY_TYPE" ||
    code === "FRONTMATTER_INVALID"
  ) {
    return "amber";
  }
  return "muted";
}

/** Worst severity across a node's issues: red > amber > muted > ok. */
export function nodeSeverity(issues) {
  if (!Array.isArray(issues) || issues.length === 0) return "ok";
  let hasAmber = false;
  for (const item of issues) {
    const code = typeof item === "string" ? item : item?.code;
    if (!code) continue;
    const severity = classifyIssueCode(code);
    if (severity === "red") return "red";
    if (severity === "amber") hasAmber = true;
  }
  return hasAmber ? "amber" : "muted";
}

// Provide global helper for chart.js 2D health coloring (`nodeSeverityOf(node)`).
globalThis.nodeSeverityOf = (node) => nodeSeverity(node?.issues);
