export function strings(locale) {
  return TEXT[String(locale ?? "").startsWith("zh") ? "zh-CN" : "en"];
}

/** The sentence for a coded refusal, or the caller's fallback. */
export function codeText(locale, code, fallback) {
  const table = strings(locale);
  return table.codes[String(code ?? "")] ?? fallback ?? table.codes.FAILED;
}
