import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { desktopAdapter, desktopClient } from './desktop-adapter.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = JSON.parse(readFileSync(join(root, 'vendor/upstream.json'), 'utf8'));
for (const [file, expected] of Object.entries(upstream.files)) {
  const actual = createHash('sha256').update(readFileSync(join(root, 'vendor/lcu', file))).digest('hex');
  if (actual !== expected) throw new Error(`Vendored source differs from pinned LCU: ${file}`);
}

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/extension.mjs'],
  outfile: 'agent/index.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  metafile: true,
  legalComments: 'inline',
  plugins: [{
    name: 'lcu-desktop-lifecycle',
    setup(bundler) {
      bundler.onLoad({ filter: /vendor\/lcu\/adapters\/pi\/index\.ts$/ }, args => ({
        contents: desktopAdapter(readFileSync(args.path, 'utf8')), loader: 'ts',
      }));
      bundler.onLoad({ filter: /vendor\/lcu\/adapters\/client\.mjs$/ }, args => ({
        contents: desktopClient(readFileSync(args.path, 'utf8')), loader: 'js',
      }));
    },
  }],
  banner: { js: "// Generated by scripts/build.mjs. See vendor/upstream.json and THIRD_PARTY_NOTICES.md.\nimport { createRequire as minihCreateRequire } from 'node:module';\nconst require = minihCreateRequire(import.meta.url);" },
});

// Include the licenses of exactly the packages whose code entered the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let directory = dirname(resolve(root, input));
  while (directory !== root && directory !== dirname(directory)) {
    const metadata = join(directory, 'package.json');
    if (existsSync(metadata)) {
      const pkg = JSON.parse(readFileSync(metadata, 'utf8'));
      if (pkg.name && pkg.version) {
        packages.set(`${pkg.name}@${pkg.version}`, { directory, pkg });
        break;
      }
    }
    directory = dirname(directory);
  }
}
const notices = ['# Third-party notices', '', `LCU source: ${upstream.repository}`, `Commit: ${upstream.commit}`, '',
  '## LCU (MIT)', '', readFileSync(join(root, 'vendor/lcu/LICENSE'), 'utf8')];
for (const [name, { directory }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const files = readdirSync(directory).filter(file => /^(licen[sc]e|notice|copyright)(\.|$)/i.test(file));
  if (!files.length) throw new Error(`No license file found for bundled dependency ${name}`);
  notices.push(`## ${name}`, '');
  for (const file of files) notices.push(readFileSync(join(directory, file), 'utf8'), '');
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), notices.join('\n').trimEnd() + '\n');
mkdirSync(join(root, 'agent'), { recursive: true });
writeFileSync(join(root, 'agent/build.json'), JSON.stringify({
  upstream: upstream.commit,
  sha256: createHash('sha256').update(readFileSync(join(root, 'agent/index.mjs'))).digest('hex'),
  dependencies: [...packages.keys()].sort(),
}, null, 2) + '\n');
console.log(`Built agent/index.mjs with ${packages.size} bundled dependencies. No runtime installation required.`);
